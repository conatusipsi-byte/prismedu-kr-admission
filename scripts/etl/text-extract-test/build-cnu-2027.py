def extract_total(line, start):
    """행 우측(>=start) region 에서 합계 추출. '1,119'/'10 8'/'1,888' 등 분리 숫자 복원."""
    region = line[start:]
    groups = re.findall(r'\d[\d, ]*\d|\d', region)
    if not groups:
        return None
    return int(groups[-1].replace(",", "").replace(" ", ""))

def assign_cells(line, colmap, total_start):
    """본문 숫자셀(합계열 제외)을 colmap 의 가장 가까운 컬럼(±TOL)에 귀속. 반환 {트랙키:합}."""
    out = {}
    for m in re.finditer(r'\d+', line):
        pos, val = m.start(), int(m.group())
        if pos >= total_start:        # 합계열 region 제외
            continue
        best = min(colmap, key=lambda c: abs(c[0] - pos))
        if abs(best[0] - pos) <= TOL:
            out[best[1]] = out.get(best[1], 0) + val
        # 멀면 미귀속 → 행합 불일치로 노출(정직)
    return out

