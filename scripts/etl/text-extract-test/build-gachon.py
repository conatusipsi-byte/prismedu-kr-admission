def stage(label, mult, comps, maxscore):
    return {"stageLabel": label, "multiplier": mult, "components": comps, "stageMaxScore": maxscore}

def mk_track(track_name, track_type, special, quota, appq, stages, csat_raw, csat_exempt, src_pages, note=None):
    t = {
        "trackName": track_name,
        "trackTypeRaw": track_type,
        "recruitmentPeriodRaw": "수시",
        "specialTypeKeyword": special,
        "quotaInitial": quota,
        "applicationQualification": appq,
        "reflectionStages": stages,
        "csatMinimumRawText": csat_raw,
        "csatMinimumExempt": csat_exempt,
        "csatRequiredAreasRawText": None,
        "prevYearResult": None,
        "sourcePages": sorted(set(src_pages)),
    }
    if note:
        t["note"] = note
    return t

