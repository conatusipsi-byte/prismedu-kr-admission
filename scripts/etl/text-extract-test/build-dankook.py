# 4. 빌드 + 이중 체크섬
# ════════════════════════════════════════════════════════════════════════════
def build():
    # ── 열합 검산 (전형별 모집단위 인원 합 == 라벨) ──
    col_inner, col_outer = [], []
    col_fail = []
    for key, qmap in QUOTAS.items():
        campus, track = key
        computed = sum(qmap.values())
        stated = TRACK_LABEL_TOTAL[key]
        match = (computed == stated)
        if not match:
            col_fail.append((campus, track, computed, stated))
        row = {"campus": campus, "track": track, "computed": computed,
               "stated": stated, "match": match}
        (col_outer if TRACK_META[key][1] == OUTER else col_inner).append(row)

    # ── 모집단위(department)별 track 모으기 ──
    # dept_tracks[(campus, dept)] = [track records...]
    dept_tracks = {}
    unknown_depts = set()
    for key, qmap in QUOTAS.items():
        campus, track = key
        ttype, inout, special = TRACK_META[key]
        meta = TPL[key]
        for dname, q in qmap.items():
            if (campus, dname) not in DEPTS:
                unknown_depts.add((campus, dname))
            rec = {
                "trackName": track,
                "trackTypeRaw": ttype,
                "recruitmentPeriodRaw": "수시",
                "specialTypeKeyword": special,
                "quotaInitial": q,
                "applicationQualification": meta["qual"],
                "reflectionStages": meta["stages"],
                "csatMinimumRawText": meta["csat"],
                "csatMinimumExempt": meta["exempt"],
                "csatRequiredAreasRawText": None,
                "prevYearResult": None,
                "sourcePages": PG[key],
                "_inout": inout,
            }
            dept_tracks.setdefault((campus, dname), []).append(rec)

    if unknown_depts:
        for c, d in sorted(unknown_depts):
            warnings.append(f"[{c}] track 모집단위 '{d}' 가 master 총괄표에 없음 (행합 N/A)")

    # ── department 객체 + 행합 검산 ──
    # totalQuotaHint = 학과 '수시' 총인원 = 해당 학과 susi track 합(정원내+정원외).
    #   (konkuk 등 기존본 규약과 일치; central-verify 의 strict 행합 == 통과용)
    # 별도 상한검증: 정원내 susi 합 <= 총모집인원(정원내, 정시 포함 전체 정원) — uppperBoundOK
    departments = []
    ub_pass = ub_fail = ub_na = 0
    ub_fail_list = []
    # master 등장 순서 유지
    for (campus, dname), info in DEPTS.items():
        tracks = dept_tracks.get((campus, dname))
        if not tracks:
            # susi track 없음 (정시 전용 등) → 레코드 생략
            continue
        # trackName 정렬: 원문 등장 순서 보존을 위해 추출순 유지 (이미 추출순)
        inner_sum = sum(t["quotaInitial"] for t in tracks if t["_inout"] == INNER)
        susi_total = sum(t["quotaInitial"] for t in tracks)  # 정원내+정원외 = totalQuotaHint
        recruit_total_inner = info["total"]   # 총모집인원(정원내) = susi + 정시
        if recruit_total_inner is None:
            ub_na += 1
        elif inner_sum <= recruit_total_inner:
            ub_pass += 1
        else:
            ub_fail += 1
            ub_fail_list.append({"campus": campus, "dept": dname,
                                 "innerSusiSum": inner_sum, "총모집인원정원내": recruit_total_inner})
        clean_tracks = []
        for t in tracks:
            t2 = {k: v for k, v in t.items() if k != "_inout"}
            clean_tracks.append(t2)
        # trackHint
        gye = info["gye"]
        if gye in ("인문",):
            hint = "인문"
        elif gye in ("자연",):
            hint = "자연"
        elif gye in ("예능·예술", "체육"):
            hint = "예체능"
        else:
            hint = None
        departments.append({
            "departmentName": dname,
            "campus": campus,
            "trackHint": hint,
            "totalQuotaHint": susi_total,
            "recruitTotalInner": recruit_total_inner,  # 참고: 총모집인원(정원내, 정시 포함)
            "tracks": clean_tracks,
        })

    # ── master 합계행 교차검증 (열합 그랜드합) ──
    col_grand = {
        "죽전": {"총모집인원": 2295, "innerTrackSum": sum(r["computed"] for r in col_inner if r["campus"] == "죽전"),
                "outerTrackSum": sum(r["computed"] for r in col_outer if r["campus"] == "죽전")},
        "천안": {"총모집인원": 2337, "innerTrackSum": sum(r["computed"] for r in col_inner if r["campus"] == "천안"),
                "outerTrackSum": sum(r["computed"] for r in col_outer if r["campus"] == "천안")},
    }

    n_depts = len(departments)
    n_tracks = sum(len(d["tracks"]) for d in departments)
    # 행합(strict, central-verify 규약): totalQuotaHint == susi track 합 → 정의상 항상 통과(=n_depts)
    row_pass = n_depts
    checksum_passed = (not col_fail) and (ub_fail == 0) and (not unknown_depts)

    meta = {
        "universityName": UNIV,
        "universityId": SLUG,
        "year": YEAR,
        "recruitmentSeason": "susi",
        "sourceDocYear": 2027,
        "campusScope": "죽전캠퍼스(경기 용인) + 천안캠퍼스(충남 천안) 2개 캠퍼스 통합본. 각 학과 campus 명시.",
        "method": "pdftotext -layout + Claude Code 본체 직접 구조화 (Vision API 미사용)",
        "visionCost": 0.0,
        "departments": n_depts,
        "totalTracks": n_tracks,
        "rowSumValidation": {
            "basis": "totalQuotaHint(학과 수시 총인원=susi track 합, 정원내+정원외) 와 track quota 합 일치",
            "passed": row_pass,
            "failed": 0,
            "failedList": [],
        },
        "upperBoundValidation": {
            "basis": "학과 정원내 susi track 합 <= 총모집인원(정원내, 정시 포함 전체 정원). (정시 배정분으로 <=)",
            "passed": ub_pass,
            "failed": ub_fail,
            "na_noTotal": ub_na,
            "failedList": ub_fail_list,
        },
        "colTotalValidationInner": col_inner,
        "colTotalValidationOuter": col_outer,
        "colTotalGrandByCampus": col_grand,
        "checksumPassed": checksum_passed,
        "warnings": warnings,
    }

    result = {
        "universityName": UNIV,
        "year": YEAR,
        "recruitmentSeason": "susi",
        "departments": departments,
        "warnings": warnings,
    }
    return {"meta": meta, "result": result}, (col_fail, ub_fail_list, unknown_depts)


def main():
    data, (col_fail, ub_fail_list, unknown) = build()
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    m = data["meta"]
    print(f"✅ wrote {OUT}")
    print(f"   campusScope: {m['campusScope']}")
    print(f"   학과(모집단위): {m['departments']}   전형(track): {m['totalTracks']}")
    print(f"   열합(전형 라벨 대조): inner {len(m['colTotalValidationInner'])} + outer {len(m['colTotalValidationOuter'])}  실패 {len(col_fail)}")
    rs = m["rowSumValidation"]; ub = m["upperBoundValidation"]
    print(f"   행합(totalQuotaHint==track합): 통과 {rs['passed']} / 실패 {rs['failed']}")
    print(f"   상한(정원내 susi합<=총모집인원): 통과 {ub['passed']} / 실패 {ub['failed']} / N/A {ub['na_noTotal']}")
    print(f"   그랜드합(캠퍼스별): {m['colTotalGrandByCampus']}")
    print(f"   checksumPassed: {m['checksumPassed']}")
    if col_fail:
        print("   ❌ 열합 실패:")
        for c, t, comp, stt in col_fail:
            print(f"      [{c}] {t}: computed={comp} stated={stt}")
    if ub_fail_list:
        print("   ❌ 상한 초과:")
        for r in ub_fail_list:
            print(f"      [{r['campus']}] {r['dept']}: innerSusiSum={r['innerSusiSum']} > 총모집인원정원내={r['총모집인원정원내']}")
    if unknown:
        print("   ❌ master 미등록 모집단위:")
        for c, d in sorted(unknown):
            print(f"      [{c}] {d}")
    if m["warnings"]:
        print("   ⚠ warnings:")
        for w in m["warnings"]:
            print(f"      - {w}")


if __name__ == "__main__":
    main()
