def make_track(key, quota, college):
    d = TRACK_DEF[key]
    if d["csat"] == "gyo":
        raw, exempt, areas = csat_gyo_main(key, college)
    else:
        raw, exempt, areas = NONE_CSAT
    sp = src(*PG_GRID, d["pg"], PG_RATIO, (PG_RATIO if not exempt else None))
    # 수능최저 적용 전형은 계열 기준표(전형 상세 페이지)가 곧 근거 → 상세페이지로 충분.
    t = {
        "trackName": d["name"],
        "trackTypeRaw": d["ttype"],
        "recruitmentPeriodRaw": "수시",
        "specialTypeKeyword": d["special"],
        "quotaInitial": quota,
        "applicationQualification": d["appq"],
        "reflectionStages": [dict(s) for s in d["stages"]],
        "csatMinimumRawText": raw,
        "csatMinimumExempt": exempt,
        "csatRequiredAreasRawText": areas,
        "prevYearResult": None,
        "sourcePages": sp,
    }
    if d.get("note"):
        t["note"] = d["note"]
    return t


