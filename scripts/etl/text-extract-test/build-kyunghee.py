# ── 인쇄 페이지(footer) → 물리 페이지 매핑 ────────────────────────────────
#   짝수면: 'NN     경희대학교 수시 신입생 모집요강' / 홀수면: '... 섹션명   NN'
#   본문은 phys = printed + 2 가 일관(검증됨). footer 우선순위로 본문만 신뢰.
printed_to_phys = {}
for i, pg in enumerate(pages, start=1):
    lines = [l for l in pg.splitlines() if l.strip()]
    found = None
    for l in lines[-2:]:
        m = re.search(r"(\d{1,3})\s+경희대학교 수시 신입생 모집요강", l)
        if m:
            found = int(m.group(1)); break
        m2 = re.search(r"(\d{1,3})\s*$", l)
        if m2 and int(m2.group(1)) < 140:
            found = int(m2.group(1))
    if found is not None and found not in printed_to_phys:
        # 본문 offset(+2) 만 채택 — TOC/표지 오탐 배제
        if i - found == 2:
            printed_to_phys[found] = i

def phys(printed):
    p = printed_to_phys.get(printed)
    if p is None:  # 폴백: 본문 offset
        p = printed + 2
    return p

